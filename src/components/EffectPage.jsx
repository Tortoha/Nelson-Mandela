function Example({ title, memory, truth }) {
  const [open, setOpen] = useState(false)
  return (
    <div className="ex">
      <h3><T>{title}</T></h3>
      <div className="exlabel">Многие помнят</div>
      <p>{memory}</p>
      {open ? (
        <>
          <div className="exlabel real">На самом деле</div>
          <p>{truth}</p>
        </>
      ) : (
        <button className="opt" onClick={() => setOpen(true)}>Показать, как было на самом деле</button>
      )}
    </div>
  )
}

